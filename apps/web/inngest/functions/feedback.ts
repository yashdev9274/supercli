import { promises as fs } from "node:fs"
import path from "node:path"

import { Octokit } from "octokit"

import {
  listPromotableNovaFeedback,
  markNovaFeedbackPromoted,
  resetNovaFeedbackPromotion,
} from "@/modules/nova/feedback/service"
import { inngest } from "../client"

const DEFAULT_REPO_OWNER = "yashdev9274"
const DEFAULT_REPO_NAME = "supercli"
const ISSUE_LABEL = "nova-feedback"

type IssueOutcome = { number: number; url: string }

function resolveRepo(): { owner: string; repo: string } {
  const repo = process.env.NOVA_FEEDBACK_REPO?.trim()
  if (repo && repo.includes("/")) {
    const [owner, name] = repo.split("/", 2)
    if (owner && name) return { owner, repo: name }
  }
  return { owner: DEFAULT_REPO_OWNER, repo: DEFAULT_REPO_NAME }
}

function resolveOctokit(): Octokit | null {
  const token =
    process.env.NOVA_FEEDBACK_GITHUB_TOKEN?.trim() ||
    process.env.GITHUB_PERSONAL_TOKEN?.trim() ||
    process.env.GITHUB_TOKEN?.trim()
  if (!token) return null
  return new Octokit({ auth: token, userAgent: "novacode-feedback/1" })
}

export const promoteNovaFeedback = inngest.createFunction(
  {
    id: "promote-nova-feedback",
    concurrency: { limit: 1 },
    retries: 3,
  },
  { cron: "*/15 * * * *" },
  async ({ step }) => {
    const enabled = (process.env.NOVA_FEEDBACK_PROMOTE_ENABLED ?? "true").toLowerCase()
    if (enabled === "false" || enabled === "0" || enabled === "off") {
      return { skipped: true, reason: "promotion_disabled" }
    }
    const candidates = await step.run("list-candidates", async () => listPromotableNovaFeedback(10))
    if (!Array.isArray(candidates) || candidates.length === 0) {
      return { promoted: 0, scanned: 0 }
    }
    const octokit = resolveOctokit()
    const repo = resolveRepo()
    if (!octokit) {
      return { promoted: 0, scanned: candidates.length, reason: "missing_token" }
    }
    let promoted = 0
    for (const row of candidates) {
      const result = await step.run(`promote-${row.id}`, async () => {
        const title = `[nova-feedback] ${row.title}`.slice(0, 240)
        const body = renderIssueBody(row)
        try {
          const issue = await octokit.rest.issues.create({
            owner: repo.owner,
            repo: repo.repo,
            title,
            body,
            labels: labelSet(row),
          })
          const url = issue.data.html_url ?? `${repo.owner}/${repo.repo}#${issue.data.number}`
          await markNovaFeedbackPromoted(row.id, { number: issue.data.number, url })
          return { ok: true, issue: { number: issue.data.number, url } satisfies IssueOutcome }
        } catch (error) {
          const message = error instanceof Error ? error.message.slice(0, 400) : "promote_failed"
          await resetNovaFeedbackPromotion(row.id, message)
          return { ok: false, error: message }
        }
      })
      if (result && typeof result === "object" && "ok" in result && result.ok) {
        promoted += 1
      }
    }
    return { promoted, scanned: candidates.length }
  },
)

export const aggregateNovaFeedbackDaily = inngest.createFunction(
  {
    id: "aggregate-nova-feedback-daily",
    retries: 1,
  },
  { cron: "5 0 * * *" },
  async ({ step }) => {
    return step.run("write-digest", async () => writeDailyDigest())
  },
)

function renderIssueBody(row: {
  id: string
  body: string
  summary: string
  severity: string
  filePath: string
  agentSessionId: string | null
  runId: string | null
  metadata: unknown
}): string {
  const parts: string[] = []
  parts.push(`**Severity:** ${row.severity}`)
  parts.push(`**Feedback id:** \`${row.id}\``)
  if (row.agentSessionId) parts.push(`**Agent session:** \`${row.agentSessionId}\``)
  if (row.runId) parts.push(`**Run:** \`${row.runId}\``)
  parts.push(`**Capture path:** \`${row.filePath}\``)
  parts.push("")
  parts.push("## Summary")
  parts.push(row.summary || "(empty)")
  parts.push("")
  parts.push("## Full timeline")
  parts.push(row.body.slice(0, 60_000))
  parts.push("")
  parts.push("---")
  parts.push("Generated by `apps/web/inngest/functions/feedback.ts` from a Nova turn captured by `/api/nova-feedback`.")
  return parts.join("\n")
}

function labelSet(row: { severity: string; metadata: unknown }): string[] {
  const labels = new Set<string>([ISSUE_LABEL])
  if (row.severity === "error") labels.add("bug")
  if (row.severity === "warn") labels.add("needs-triage")
  labels.add("area:agent-runtime")
  return [...labels]
}

type DailyDigestRow = {
  severity: string
  title: string
  summary: string
  filePath: string
  outcome: string
  improvements: number
  createdAt: Date
}

async function writeDailyDigest(): Promise<{ wrote: boolean; path: string | null }> {
  try {
    const prismaModule = await import("@super/db")
    const prisma = prismaModule.default
    const since = new Date(Date.now() - 24 * 60 * 60 * 1000)
    const rows: DailyDigestRow[] = (await prisma.novaFeedback.findMany({
      where: { createdAt: { gte: since } },
      orderBy: { createdAt: "desc" },
      take: 500,
      select: { severity: true, title: true, summary: true, filePath: true, createdAt: true, status: true, metadata: true },
    })).map((row) => ({
      severity: row.severity,
      title: row.title,
      summary: row.summary,
      filePath: row.filePath,
      createdAt: row.createdAt,
      outcome: row.status,
      improvements: Array.isArray((row.metadata as { improvements?: unknown[] })?.improvements)
        ? ((row.metadata as { improvements?: unknown[] }).improvements as unknown[]).length
        : 0,
    }))
    const counts = rows.reduce<Record<string, number>>((acc, row) => {
      acc[row.severity] = (acc[row.severity] ?? 0) + 1
      return acc
    }, {})
    const total = rows.length
    const today = new Date().toISOString().slice(0, 10)
    const digestRoot = path.resolve(process.cwd(), ".nova-feedback")
    await fs.mkdir(digestRoot, { recursive: true }).catch(() => undefined)
    const digestPath = path.join(digestRoot, `digest-${today}.md`)
    const lines: string[] = []
    lines.push(`# Nova feedback digest — ${today}`)
    lines.push("")
    lines.push(`Captured ${total} exchange${total === 1 ? "" : "s"} in the last 24 hours.`)
    lines.push("")
    lines.push(`- info: ${counts["info"] ?? 0}`)
    lines.push(`- warn: ${counts["warn"] ?? 0}`)
    lines.push(`- error: ${counts["error"] ?? 0}`)
    lines.push("")
    if (rows.length === 0) {
      lines.push("_No feedback captured today._")
    } else {
      lines.push("## Recent exchanges")
      lines.push("")
      for (const row of rows.slice(0, 25)) {
        lines.push(`- **${row.severity.toUpperCase()}** — _${row.title.replace(/\n/g, " ").slice(0, 180)}_ (${row.outcome}, ${row.improvements} improvements)`)
        if (row.summary) lines.push(`  - ${row.summary.slice(0, 220).replace(/\n/g, " ")}`)
        lines.push(`  - ${row.filePath}`)
      }
      lines.push("")
      lines.push("---")
      lines.push(`generated by aggregate-nova-feedback-daily on ${new Date().toISOString()}`)
    }
    await fs.writeFile(digestPath, lines.join("\n"), "utf8")
    return { wrote: true, path: digestPath }
  } catch (error) {
    return { wrote: false, path: null }
  }
}
