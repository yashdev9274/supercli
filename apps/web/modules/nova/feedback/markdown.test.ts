import { describe, expect, test } from "bun:test"

import {
  buildDefaultImprovements,
  deriveSeverityFromOutcome,
  renderNovaFeedbackMarkdown,
} from "./markdown"

describe("nova feedback markdown renderer", () => {
  test("produces a coherent header + summary for empty events", () => {
    const md = renderNovaFeedbackMarkdown({
      title: "Investigate failing tests",
      exchange: {
        agentSessionId: "sess_1",
        runId: "run_1",
        surface: "web",
        provider: "openai",
        model: "gpt-4.1",
        mode: "agent",
        startedAt: "2026-11-05T10:00:00Z",
      },
      summary: "Tests failed because the test harness lacked an .env file",
      severity: "warn",
      events: [],
      improvements: buildDefaultImprovements([{ kind: "tool_failure", detail: "ran tests but env missing" }]),
      perceivedIssues: [{ kind: "tool_failure", detail: "ran tests but env missing" }],
      feedbackId: "fb_1",
    })
    expect(md).toContain("# Nova turn — Investigate failing tests")
    expect(md).toContain("Severity: ⚠️ warn")
    expect(md).toContain("Tests failed because the test harness lacked an .env file")
    expect(md).toContain("## Suggested improvements")
    expect(md).toContain("generated by /api/nova/feedback")
  })

  test("renders issues inline with the suggested improvement", () => {
    const md = renderNovaFeedbackMarkdown({
      title: "Empty shell call",
      exchange: { agentSessionId: null, runId: null, provider: null, model: null, mode: null, startedAt: null },
      summary: "",
      severity: "info",
      events: [],
      improvements: buildDefaultImprovements([{ kind: "empty_tool_result", detail: "shell returned empty" }]),
      perceivedIssues: [{ kind: "empty_tool_result", detail: "shell returned empty" }],
      feedbackId: "fb_x",
    })
    expect(md).toMatch(/Detect empty tool results/)
    expect(md).toMatch(/shell returned empty/)
  })

  test("deriveSeverityFromOutcome escalates on tool failures", () => {
    expect(deriveSeverityFromOutcome("completed", [])).toBe("info")
    expect(deriveSeverityFromOutcome("failed", [])).toBe("error")
    expect(deriveSeverityFromOutcome("completed", [{ kind: "tool_failure", detail: "x" }])).toBe("warn")
  })
})
